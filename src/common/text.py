def html_to_text(h: str) -> str:
    if not h:
        return ""
    h = re.sub(r"(?is)<(script|style|pre|figure|svg).*?</\1>", " ", h)
    h = re.sub(r"(?i)</?(strong|em|b|i|u|s|code|a|span|del|ins|sup|sub|small|mark|kbd)[^>]*>", "", h)
    h = re.sub(r"(?i)<br\s*/?>", " ", h)
    h = re.sub(r"(?i)</(p|div|li|h[1-6]|tr|blockquote)>", " ", h)
    h = re.sub(r"(?s)<[^>]+>", " ", h)
    txt = html.unescape(h).replace("\ufffd", " ")
    txt = URL_RE.sub(" ", txt)
    txt = EMAIL_RE.sub(" ", txt)
    return WS_RE.sub(" ", txt).strip()


def clean_text(t: str) -> str:
    t = (t or "").lower()
    t = CODE_FENCE_RE.sub(" ", t)
    t = INLINE_CODE_RE.sub(" ", t)
    t = re.sub(r"\bcan['’]t\b", "can not", t)
    t = re.sub(r"\bwon['’]t\b", "will not", t)
    t = re.sub(r"n['’]t\b", " not", t)
    t = re.sub(r"['’](?:re|ve|ll|d|m)\b", " ", t)
    t = re.sub(r"['’]s\b", " ", t)
    t = t.replace("'", "").replace("’", "")
    t = BOILER_RE.sub(" ", t)
    t = FOOTER_RE.sub(" ", t)
    for p in TEMPLATE_PHRASES:
        t = t.replace(p, " ")
    t = PATH_RE.sub(" ", t)
    t = STACK_RE.sub(" ", t)
    # 逐句删掉诊断页脚
    segs = re.split(r"(?<=[.!?])\s+|\n+", t)
    t = " ".join(s for s in segs if s and not DIAG_RE.search(s))
    t = URL_RE.sub(" ", t)
    t = EMAIL_RE.sub(" ", t)
    t = NUM_RE.sub(" ", t)
    return WS_RE.sub(" ", t).strip()


def _singular(w: str) -> str:
    if len(w) <= 4:
        return w
    if w.endswith("ies") and len(w) > 5:
        return w[:-3] + "y"
    if w.endswith(("sses", "shes", "ches", "xes")):
        return w[:-2]
    if w.endswith("s") and not w.endswith(("ss", "us", "is")):
        return w[:-1]
    return w


def audit_text(t: str) -> str:
    """给人工回读用的可读片段：去 HTML/代码/模板标题，但保留数字与语义。"""
    t = html_to_text(t)
    t = CODE_FENCE_RE.sub(" [code] ", t)
    t = FOOTER_RE.sub(" ", t)
    t = re.sub(r"#{1,6}\s*", " ", t)
    t = re.sub(r"(?:what|which) (?:version|subscription|platform|variant|terminal|model|ide|os)\b[^?]{0,140}\?", " ", t, flags=re.I)
    t = re.sub(r"what issue are you seeing\??", " ", t, flags=re.I)
    t = re.sub(r"(?m)^\s*[-*]\s*\[[ xX]\]\s*", " ", t)
    t = re.sub(r"[ \t]+", " ", t)
    t = re.sub(r"\s*\n\s*", " ", t)
    return t.strip()


def tokenize(t: str) -> list[str]:
    toks = []
    for w in TOKEN_RE.findall((t or "").lower()):
        w = w.strip("-+._")
        if len(w) < 2 or w in STOP or w.isdigit():
            continue
        w = _singular(w)
        if len(w) < 2 or w in STOP:
            continue
        if toks and toks[-1] == w:
            continue
        toks.append(w)
    return toks


def token_text(t: str) -> str:
    return " ".join(tokenize(t))


def char_stats(t: str) -> dict:
    return {
        "chars": len(t or ""),
        "words": len((t or "").split()),
        "has_code": int("```" in (t or "") or "<code" in (t or "").lower()),
    }
